"""Typed payer-call bodies: recordings, transcription jobs, and transcripts.

Implements: US-11.1 (``CallRecording``, ``CallTranscript``, ``TranscriptionJob``, ``PayerCall``,
``CallAdded``, ``TranscriptionQueued``, and the recording limits). Rules: ES-1 (Pydantic v2,
``extra="forbid"``, frozen), BR-2 (recordings and transcripts travel pane → ``plugin_api.py`` →
worker only), BR-14 (``CallRecording.filename`` and ``CallTranscript`` are case content: sealed at
rest, never logged, never in an event; ``TranscriptionJob`` holds IDs, a state, dates, and an error
code only, so it may be written to the queue file).

This module imports nothing heavier than Pydantic, so the gateway can use it.
"""

from __future__ import annotations

import secrets
from typing import Final, Literal

from pydantic import BaseModel, ConfigDict, Field

from claimcoach.api.models import ErrorCode
from claimcoach.calls.window import TranscriptionWindow
from claimcoach.corpus.types import CaseId, ProfileName, Timestamp

__all__ = [
    "CALL_ID_PATTERN",
    "MAX_CALL_BODY",
    "MAX_CALL_BYTES",
    "MAX_INSTRUCTIONS",
    "MAX_TRANSCRIPT_CHARS",
    "TRANSCRIPTION_JOB_PATTERN",
    "AudioFormat",
    "CallAdded",
    "CallRecording",
    "CallTranscript",
    "PayerCall",
    "TranscriptionJob",
    "TranscriptionQueued",
    "TranscriptionState",
    "new_call_id",
    "new_transcription_job_id",
    "transcript_item_id",
]

MAX_CALL_BYTES: Final = 128 * 1024 * 1024
"""Largest accepted recording: an hour of 16 kHz 16-bit mono WAV is about 115 MiB."""
MAX_CALL_BODY: Final = MAX_CALL_BYTES + 64 * 1024
"""Largest multipart body read: the recording plus its framing and headers."""
MAX_TRANSCRIPT_CHARS: Final = 1_000_000
"""Longest transcript stored: hours of speech; a longer reply is not a transcript."""
MAX_INSTRUCTIONS: Final = 10
CALL_ID_PATTERN: Final = r"^call_[0-9a-f]{16}$"
"""Call IDs: random, generated by ClaimCoach (``new_call_id``)."""
TRANSCRIPTION_JOB_PATTERN: Final = r"^trj_[0-9a-f]{16}$"
"""Transcription job IDs: random; not case-job IDs, which live only in memory."""

AudioFormat = Literal["wav", "mp3", "flac", "m4a"]
"""What a recording is, decided from its bytes (``calls.audio.sniff_audio``)."""

TranscriptionState = Literal["queued", "running", "done", "failed"]
"""Where a transcription job is: waiting for the window, transcribing, or ended."""


def new_call_id() -> str:
    """Return a new opaque call ID."""
    return f"call_{secrets.token_hex(8)}"


def new_transcription_job_id() -> str:
    """Return a new opaque transcription job ID."""
    return f"trj_{secrets.token_hex(8)}"


def transcript_item_id(call_id: str) -> str:
    """Return the case-item ID of a call's one transcript."""
    return f"trn_{call_id.removeprefix('call_')}"


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class CallRecording(_Strict):
    """A payer-call recording attached to a case.

    Attributes:
        call_id: Opaque ID.
        format: What the audio is, from its bytes.
        filename: The uploaded file's name, or ``None`` (may be PHI; sealed, shown in the pane).
        content_type: The declared media type, for display only.
        size_bytes: Its size.
        added_at: When it was attached.
    """

    call_id: str = Field(pattern=CALL_ID_PATTERN)
    format: AudioFormat
    filename: str | None = Field(default=None, min_length=1, max_length=255)
    content_type: str = Field(min_length=1, max_length=127)
    size_bytes: int = Field(ge=1)
    added_at: Timestamp


class CallTranscript(_Strict):
    """A call's transcript and what was read from it (case content; sealed at rest).

    Attributes:
        call_id: The call it transcribes.
        text: The transcript.
        reference_number: The call's reference number, read from the transcript, if one was said.
        rep_instructions: The rep's instructions, read from the transcript, in order.
        truncated: The model stopped at its length limit before the call ended (calls longer
            than about 30 minutes); the end of the call, often where the reference number is
            repeated, is missing.
        transcribed_at: When the transcription finished.
    """

    call_id: str = Field(pattern=CALL_ID_PATTERN)
    text: str = Field(min_length=1, max_length=MAX_TRANSCRIPT_CHARS)
    reference_number: str | None = Field(default=None, min_length=4, max_length=32)
    rep_instructions: list[str] = Field(default_factory=list, max_length=MAX_INSTRUCTIONS)
    truncated: bool = False
    transcribed_at: Timestamp


class TranscriptionJob(_Strict):
    """One call's transcription job, as the queue file stores it (no case content).

    Attributes:
        job_id: Opaque ID.
        profile: The case's profile.
        case_id: The case.
        call_id: The call.
        state: Where the job is.
        window: The profile's window; for a queued job as views read it, the current setting.
        queued_at: When it was queued.
        not_before: When it may start: now inside the window, else the window's next start
            (refreshed for a queued job whenever it is read).
        started_at: When it last started.
        finished_at: When it ended.
        error_code: Why it failed.
    """

    job_id: str = Field(pattern=TRANSCRIPTION_JOB_PATTERN)
    profile: ProfileName
    case_id: CaseId
    call_id: str = Field(pattern=CALL_ID_PATTERN)
    state: TranscriptionState = "queued"
    window: TranscriptionWindow
    queued_at: Timestamp
    not_before: Timestamp
    started_at: Timestamp | None = None
    finished_at: Timestamp | None = None
    error_code: ErrorCode | None = None


class PayerCall(_Strict):
    """A call as the pane shows it: the recording, its latest job, and its transcript.

    Attributes:
        recording: The recording.
        transcription: Its latest transcription job, once one was queued.
        transcript: Its transcript, once a transcription finished.
    """

    recording: CallRecording
    transcription: TranscriptionJob | None = None
    transcript: CallTranscript | None = None


class CallAdded(_Strict):
    """The answer to a recording upload.

    Attributes:
        ok: Always ``True``.
        case_id: The case.
        call: The attached recording.
    """

    ok: Literal[True] = True
    case_id: CaseId
    call: CallRecording


class TranscriptionQueued(_Strict):
    """The answer to ``POST /cases/{case_id}/calls/{call_id}/transcribe``.

    Attributes:
        ok: Always ``True``.
        case_id: The case.
        job: The call's job: the one just queued, or the one already queued or running.
    """

    ok: Literal[True] = True
    case_id: CaseId
    job: TranscriptionJob
