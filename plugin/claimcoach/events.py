"""Typed payloads of the ``plugin.claimcoach.*`` events and the one function that sends them.

Implements: US-3.4 (event payloads carry no PHI). Rules: ES-1 (every event payload is a Pydantic
model), BR-14 (events are redacted — here by construction: no field can hold free text), PC-4
(push updates use ``broadcast_plugin_event("claimcoach", "<event>", payload)``, received by the
desktop half with ``host.onEvent``).

Every string field is either a fixed enum or an opaque ID ClaimCoach generates (``case_`` or
``job_`` followed by 16 lowercase hex digits), so a name, a date, an SSN, an MRN, a member ID, or
any document text fails validation before anything is sent: an ID is never a natural key.
``test_us_3_4_event_fields_cannot_carry_text`` walks the JSON schema to keep it that way.
"""

from __future__ import annotations

import secrets
from collections.abc import Callable
from typing import Any, ClassVar, Final, Literal

from pydantic import BaseModel, ConfigDict, Field

from claimcoach import PLUGIN_NAME
from claimcoach.api.models import ErrorCode
from claimcoach.logs import get_logger

__all__ = [
    "CASE_ID_PATTERN",
    "JOB_ID_PATTERN",
    "CaseProgressEvent",
    "CaseStage",
    "EventSink",
    "PluginEvent",
    "Report",
    "hermes_sink",
    "new_case_id",
    "new_job_id",
    "publish",
]

CASE_ID_PATTERN: Final = r"^case_[0-9a-f]{16}$"
"""Case IDs: random, generated by ClaimCoach (``new_case_id``), never derived from a document."""
JOB_ID_PATTERN: Final = r"^job_[0-9a-f]{16}$"
"""Pipeline job IDs: random, generated by ClaimCoach (``new_job_id``)."""


def new_case_id() -> str:
    """Return a new opaque case ID."""
    return f"case_{secrets.token_hex(8)}"


def new_job_id() -> str:
    """Return a new opaque job ID."""
    return f"job_{secrets.token_hex(8)}"


CaseStage = Literal[
    "uploaded", "extracting", "redacting", "classifying", "explaining", "drafting", "done", "failed"
]
"""Pipeline stages a case goes through (EPIC-5 to EPIC-7)."""

Report = Callable[[CaseStage, float], None]
"""A job step's progress callback: each stage and the fraction of the job done."""

EventSink = Callable[[str, str, dict[str, Any]], None]
"""``broadcast_plugin_event(plugin_id, event, payload)``."""

_log = get_logger("claimcoach.events")


class PluginEvent(BaseModel):
    """Base of every event payload; ``EVENT`` is the name after ``plugin.claimcoach.``."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    EVENT: ClassVar[str]


class CaseProgressEvent(PluginEvent):
    """Progress of one case through the pipeline (``plugin.claimcoach.case.progress``).

    Attributes:
        case_id: The case.
        job_id: The pipeline job working on it.
        stage: Current stage.
        progress: Fraction of the whole pipeline done, 0 to 1.
        error_code: Why the case failed, when ``stage`` is ``failed``.
    """

    EVENT: ClassVar[str] = "case.progress"

    case_id: str = Field(pattern=CASE_ID_PATTERN)
    job_id: str = Field(pattern=JOB_ID_PATTERN)
    stage: CaseStage
    progress: float = Field(ge=0, le=1)
    error_code: ErrorCode | None = None


def hermes_sink() -> EventSink | None:
    """Return Hermes' ``broadcast_plugin_event`` inside the gateway, ``None`` elsewhere."""
    try:
        from hermes_cli.plugin_events import broadcast_plugin_event  # noqa: PLC0415
    except ImportError:
        return None
    sink: EventSink = broadcast_plugin_event
    return sink


def publish(event: PluginEvent, sink: EventSink | None = None) -> bool:
    """Send ``event`` to every connected desktop client.

    Args:
        event: A validated payload model.
        sink: Where to send it; defaults to Hermes' broadcaster.

    Returns:
        Whether a sink took the event (``False`` outside the gateway).
    """
    target = sink or hermes_sink()
    if target is None:
        _log.info("event %s not sent: no gateway in this process", event.EVENT)
        return False
    target(PLUGIN_NAME, event.EVENT, event.model_dump(mode="json"))
    return True
